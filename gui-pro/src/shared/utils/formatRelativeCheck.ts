/**
 * formatRelativeCheck — время последней удачной проверки обновлений, «по-человечески».
 *
 * Экран «О программе» показывает не отметку времени, а фразу: «только что», «5 минут назад»,
 * «вчера». Так решено потому, что читатель у этой строки нетехнический: «вчера» он берёт с одного
 * взгляда, а «26.08.2026 13:30» ему сначала надо вычесть из текущего времени, чтобы понять — это
 * было давно или только что. Отметка времени отвечает на вопрос «когда именно», а карточке нужен
 * ответ на «давно ли».
 *
 * Сосед `formatLastUpdated.ts` НАМЕРЕННО не расширялся и не переиспользуется: это единый
 * абсолютный формат «ДД.ММ.ГГГГ ЧЧ:ММ» для карточек вкладки «Сервис», где как раз важно «когда
 * именно» (лог сервера, проверка IP). Две разные задачи в одной функции разошлись бы при первой
 * же правке одной из них.
 *
 * Функция возвращает КЛЮЧ и значения подстановки, а не готовую строку. Фразы — пользовательский
 * текст, значит они должны переводиться, а `t()` вызывается на границе отрисовки — тот же приём,
 * что и `REASON_CODE_I18N` в `hooks/vpnEventHelpers.ts`: производитель отдаёт стабильный
 * идентификатор, локализует потребитель.
 *
 * Ключи выписаны ЛИТЕРАЛАМИ в каждой ветке и никогда не собираются из кусков: сторож мёртвых
 * ключей (`scripts/i18n-dead-keys.cjs`) ищет подстроку по всему коду, и собранный ключ он не
 * увидит — он отчитается о нём как о мёртвом.
 */

/** Ключ фразы и её числовая подстановка (если фраза вообще берёт число). */
export interface RelativeCheckPhrase {
  key: string;
  values?: Record<string, number>;
}

const MINUTE_MS = 60_000;
const HOUR_MS = 60 * MINUTE_MS;
const DAY_MS = 24 * HOUR_MS;

/** Полночь по МЕСТНОМУ времени: «вчера» — это про календарь пользователя, а не про UTC. */
function startOfLocalDay(d: Date): number {
  return new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime();
}

/**
 * @param iso  отметка последней удачной проверки (`UpdateInfo.lastChecked`) или её отсутствие
 * @param now  точка отсчёта; параметр существует ради детерминированных тестов — в бою не
 *             передаётся, и функция берёт текущее время сама
 * @returns    ключ фразы со значениями подстановки, либо `null` — тогда строка не рисуется вовсе
 *             (ни прочерка, ни заглушки: приложению нечего сказать, и оно молчит)
 */
export function formatRelativeCheck(
  iso: string | null | undefined,
  now: Date = new Date(),
): RelativeCheckPhrase | null {
  if (!iso) return null;

  const then = new Date(iso);
  // `new Date("не дата")` даёт Invalid Date, а не бросает исключение. Без этой проверки дальше
  // поехал бы NaN и фраза вышла бы «NaN минут назад».
  if (Number.isNaN(then.getTime())) return null;

  const elapsed = now.getTime() - then.getTime();

  // Будущее читается как «только что». Часы на машине могут отстать или прыгнуть назад после
  // синхронизации; проверка при этом действительно была, и честнее сказать «только что», чем
  // «-7 минут назад».
  if (elapsed < MINUTE_MS) return { key: "about.when_just_now" };

  if (elapsed < HOUR_MS) {
    return { key: "about.when_minutes", values: { count: Math.floor(elapsed / MINUTE_MS) } };
  }

  // До суток считаем часами, даже если полночь уже перешли: внутри суток точное расстояние
  // полезнее, чем «вчера», а «вчера» начинается там, где число часов перестаёт держаться в голове.
  if (elapsed < DAY_MS) {
    return { key: "about.when_hours", values: { count: Math.floor(elapsed / HOUR_MS) } };
  }

  // Дальше суток считаем календарными днями, а не делением на 24 часа: «вчера» — это вчерашняя
  // дата, а не «между 24 и 48 часами назад». Math.round гасит переход на летнее время, когда
  // сутки длятся 23 или 25 часов и деление дало бы 0.96 или 1.04.
  const dayDiff = Math.round((startOfLocalDay(now) - startOfLocalDay(then)) / DAY_MS);
  if (dayDiff <= 1) return { key: "about.when_yesterday" };
  return { key: "about.when_days", values: { count: dayDiff } };
}
