/**
 * parseReleaseNotes — достаёт из файла заметок о выпусках раздел одной версии.
 *
 * Файл `shared/release-notes/RELEASE_NOTES.ru.md` разбит на части заголовками вида
 * `## Версия X.Y.Z`. Заголовок — **якорь разбора, а не содержимое**: строку «Версия X.Y.Z» окно
 * «Что нового» рисует само из номера версии, поэтому заголовок из тела раздела вырезается. Оставь
 * его внутри — и номер версии покажется на экране дважды.
 *
 * Отсутствие раздела — это `null`, а не пустая строка, и это тоже про экран: `null` — плитка
 * «заметок для этой версии нет», а пустая строка отрисовала бы пустой раздел под заголовком версии,
 * то есть ровно то состояние, которого дизайн не допускает. По той же причине раздел с телом из
 * одних пробелов тоже даёт `null`.
 *
 * Функция принимает текст аргументом, а не импортирует файл сама: так она остаётся чистой, а
 * приложение, тесты и будущие вызовы могут скормить ей что угодно. Боевой импорт файла живёт на
 * стороне вызова.
 *
 * Тот же разбор продублирован в `scripts/release-notes-section.cjs` — он порождает описание
 * GitHub-выпуска из этого же файла (D-20: один источник правды на два места показа). Общий модуль
 * между `gui-pro/src` (ESM, TypeScript) и корневым CJS-скриптом стоил бы отдельного шага сборки
 * ради десяти строк, поэтому дублирование намеренное, а стережёт его тест
 * `releaseNotesGenerator.parity.test.ts`: он требует побайтового совпадения двух реализаций.
 */

/**
 * Якорь заголовка версии.
 *
 * `\r?$` обязателен: в репозитории `core.autocrlf = true` и без `.gitattributes`, поэтому в свежем
 * клоне тот же файл лежит с CRLF, а в этом рабочем дереве — с LF. Без учёта `\r` разбор работал бы
 * у одного разработчика и молча возвращал `null` у другого.
 *
 * Номер версии захватывается целиком, одной строкой, и дальше сравнивается на полное равенство —
 * ни одна сторона не проверяется как префикс другой, поэтому `3.0` не может подобрать раздел
 * `3.0.0`, а `3.0.0` — раздел `3.0`.
 */
const VERSION_HEADING = /^##[ \t]+Версия[ \t]+([0-9]+(?:\.[0-9]+)*)[ \t]*\r?$/gm;

export function parseReleaseNotes(raw: string, version: string): string | null {
  // Свежий RegExp на каждый вызов: у литерала с флагом `g` есть изменяемый lastIndex, общий для всех
  // вызовов, — переиспользование сделало бы функцию нечистой и зависящей от порядка вызовов.
  const heading = new RegExp(VERSION_HEADING.source, "gm");

  const sections: { version: string; headingStart: number; bodyStart: number }[] = [];
  let match: RegExpExecArray | null;
  while ((match = heading.exec(raw)) !== null) {
    sections.push({
      version: match[1],
      headingStart: match.index,
      bodyStart: match.index + match[0].length,
    });
  }

  for (let i = 0; i < sections.length; i += 1) {
    if (sections[i].version !== version) continue;

    // Тело — до начала следующего заголовка версии (или до конца файла у последнего раздела).
    // Позиция раздела в файле на результат не влияет: границы считаются от соседей, а не от начала.
    const end = i + 1 < sections.length ? sections[i + 1].headingStart : raw.length;
    const body = raw.slice(sections[i].bodyStart, end).trim();
    return body.length > 0 ? body : null;
  }

  return null;
}
